# v1.3.8 —— 修 v1.3.7 遗留：同型号同序列号两颗（真机两颗 DECXIN：序列号都是
#   01.00.00）的 by-id 链接**归属会在重新枚举时翻转**（谁后注册谁拿到），于是
#   同一台相机在 `uvc:usb-1-5` 与 `uvc:usb-DECXIN_..._01.00.00` 两个 key 之间
#   跳 —— 面板表现为设备消失又出现（真机 logs/main.log 抓到 `Connected:
#   DECXIN_head` 紧跟 `Disconnected: DECXIN DECXIN CAMERA`）、用户起的名字丢失。
#   v1.3.7 只让「拿不到链接」那颗退拓扑路径，拿到链接那颗仍用 by-id ⇒ 翻转时
#   两颗一起跳，问题没解决。现改为：判定前缀被共用后**两颗都退拓扑路径**。
#   判据不能是「数前缀重复」—— 任一时刻只有一台真拿到链接，另一台压根进不了
#   计数；改为「一台没链接的物理设备，其 (厂商, 型号) 与另一台有链接的相同」
#   （同型号但序列号不同的两台各有各的链接，不会被误判降级）。
#   代价：那颗单插 DECXIN 的 key 从 by-id 形式变成 `uvc:usb-1-5`，data/
#   device_names.json 里挂在旧 key 下的名字需重命名一次（旧 key 已不再产生）。
