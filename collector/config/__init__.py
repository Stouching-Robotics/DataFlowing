# v1.3.9 —— 连夹爪时自动把 DECXIN 的曝光/白平衡写回「自动」（v1.3.7「画面暗」
#   的自动化版：此前每接一台新夹爪都要人工跑一次 v4l2-ctl）。暗的根因不在采集
#   链，而在**相机机身**：`auto_exposure=1`(手动)+`white_balance_automatic=0`
#   会让它永久停在出厂 156/10000（1.56% 积分）的积分上，而这个状态**存在相机
#   里、跨重插保持** ⇒ 修好 001 那台对 002 一点用都没有。主程序侧此前根本没有
#   写入口（libuvc 服务只有 `uvc_set_altsetting_override`；
#   `core.camera._apply_exposure_to` 是 OpenCV 通用相机那条路，夹爪 RGB 不经过），
#   所以只能人工介入。新增 `core/gripper/decxin_exposure.py`：只认 1bcf:2d4f，
#   **每次连接**把所有 DECXIN 读一遍，已经是自动档就一个字节都不写（省一次 USB
#   往返，也不会每连一次就把用户特意设的手动曝光抹掉）。调用点在
#   `bridge._open_run`，且**必须早于 `UvcCameraServiceManager.select()`**：服务
#   一开设备就被 libusb 拿走、内核 uvcvideo 被摘、/dev/videoN 随之注销，之后所有
#   V4L2 ioctl 都会失败 —— 这正是「要停掉主程序才能 v4l2-ctl」的由来。纯附加
#   动作，失败只记日志（画面暗是小事，连不上是大事）。DECXIN 的 auto_exposure
#   菜单是 1=手动 / 3=光圈优先、**没有 0**（写 0 得 EINVAL），故候选序 3/0/2；
#   Sightac 触觉相机（0c45:636f）绝不触碰，它的 AE=1/AWB=0/6500K 是原厂存储态。
#   同一版还进了三样：ORB-SLAM **构建源**搬进 `core/gripper/orb_slam_src/`
#   （原先只活在不上传的 online/ 里，四个崩溃家族的修复全在那份源码上，online
#   一删就只剩二进制、一行都改不动；生产**尚未**从新树安装、真机未验）；契约测试
#   补按模块加载器（11 份里有 4 份没有 `unittest.main()`，直跑 rc=0 零输出＝假绿）；
#   `tools/diag_frame_trace.py` 把 v1.3.2 的陈旧帧问题**取证定案为 H2**（旧帧被
#   重投递，不是只戳错）—— 判据必须用边缘图 + 同窗对照，裸 mad 会判错，守卫的
#   「丢帧」处置是对的，**不该把戳修回来**。
